export const localeStorageKey = "ytloadster.locale";

export function getInitialLocale(): AppLocale {
  try {
    const stored = window.localStorage.getItem(localeStorageKey);
    if (stored === "ru" || stored === "en") return stored;
  } catch {
    // Fall back to the system language when WebView storage is unavailable.
  }
  return getSystemLocale();
}

export function getSystemLocale(): AppLocale {
  try {
    const language = navigator.languages?.[0] || navigator.language;
    return language.split(/[-_]/, 1)[0]?.toLowerCase() === "ru" ? "ru" : "en";
  } catch {
    return "en";
  }
}

export function saveLocale(locale: AppLocale) {
  try {
    window.localStorage.setItem(localeStorageKey, locale);
  } catch {
    // Language switching remains available for the current session.
  }
}

export function localizeTechnicalText(value: string, locale: AppLocale) {
  if (locale === "ru") return value;
  return value.replace(/\bМБ\b/g, "MB").replace(/\bГБ\b/g, "GB").replace(/\bКБ\b/g, "KB");
}

export function translate(locale: AppLocale, key: TranslationKey, values: TranslationValues = {}) {
  const template = (locale === "en" ? en : ru)[key];
  return Object.entries(values).reduce(
    (result, [name, value]) => result.split(`{{${name}}}`).join(String(value)),
    template,
  );
}

type I18nValue = {
  locale: AppLocale;
  t: Translate;
};

const I18nContext = createContext<I18nValue>({
  locale: "ru",
  t: (key, values) => translate("ru", key, values),
});

export function I18nProvider({ locale, children }: { locale: AppLocale; children: ReactNode }) {
  return (
    <I18nContext.Provider value={{ locale, t: (key, values) => translate(locale, key, values) }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
